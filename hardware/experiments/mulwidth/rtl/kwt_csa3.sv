// 28位三压二压缩器：把三个补码数压成和位与进位位，供PE的多乘积压缩树逐级使用。
// 只做逐位奇偶/多数运算，不传播进位；最终CPA统一由kwt_acc28完成。
module kwt_csa3 (
    input logic [27:0] a,b,c, // 三个待压缩操作数（乘积已符号扩展并屏蔽零通道）
    output logic [27:0] s,co // 和位、左移一位后的进位位
);
    assign s = a ^ b ^ c; // 三个输入的本位奇偶和。
    assign co = ((a&b)|(a&c)|(b&c)) << 1; // 至少两个1的位产生进位，移到高一位；第28位外溢丢弃。
endmodule
